const permissionKeySet = new Set(PERMISSION_KEYS);

function isPermissionKey(permissionKey) {
  return permissionKeySet.has(permissionKey);
}

function deriveModuleDataScopes({ positionLevel, functionalRoleKeys = [] }) {
  const scopeByModule = Object.fromEntries(
    DATA_SCOPE_MODULE_VALUES.map((moduleKey) => [moduleKey, DATA_SCOPES.ORG_UNIT])
  );

  if (
    positionLevel === POSITION_LEVELS.DEPARTMENT_MANAGER ||
    positionLevel === POSITION_LEVELS.DEPARTMENT_DEPUTY_OR_ASSISTANT
  ) {
    for (const moduleKey of DATA_SCOPE_MODULE_VALUES) {
      scopeByModule[moduleKey] = DATA_SCOPES.TEAM;
    }
  }

  const roleSet = new Set(functionalRoleKeys);
  if (roleSet.has(FUNCTIONAL_ROLE_KEYS.ASSET_ADMIN)) {
    scopeByModule[DATA_SCOPE_MODULES.EQUIPMENT] = DATA_SCOPES.TEAM;
  }
  if (roleSet.has(FUNCTIONAL_ROLE_KEYS.ATTENDANCE_OFFICER)) {
    scopeByModule[DATA_SCOPE_MODULES.REPORT_ATTENDANCE] = DATA_SCOPES.TEAM;
  }

  return DATA_SCOPE_MODULE_VALUES.map((moduleKey) => ({
    moduleKey,
    scope: scopeByModule[moduleKey]
  }));
}

